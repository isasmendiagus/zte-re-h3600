/*
 * ZTE ZXIC ZX279128S — integrated Ethernet driver.
 *
 * The SoC integrates an on-chip 4-port switch fed by four built-in
 * gigabit PHYs (driver: drivers/net/phy/phy-zte-gephy.c, talked to via
 * drivers/net/mdio/mdio-zte.c) and a packet processor pipeline that
 * delivers frames to the host through an IDM DMA ring:
 *
 *   RJ45 → GePHY → MAC[0..3] → on-chip switch (SW)
 *                            → packet processor (PP)
 *                            → DDR via PP_AXI / IDM ring
 *
 * This driver currently owns the whole pipeline as a single platform
 * driver. A future DSA split would expose 4 user-port netdevs + one
 * CPU-conduit; until then `eth0` is the CPU port (named "sw") and
 * `idm0`/`idm1` are the two wifi-offload conduits.
 *
 * MMIO map driven from DT (compatible "zte,zx279128s-eth"):
 *   reg[pon] : 0x92000000 + 0x1c0000   PON-side regs (CLA, FDB, …)
 *   reg[npp] : 0x921c0000 + 0x200000   NPP/IDM/TM/PP unified window
 *     +0x008000  IDM (descriptor rings, IRQ, RX/TX kick)
 *     +0x040000  MAC0..3                ← user ports
 *     +0x140000  MAC4 (RGMII WAN — unused on H3600)
 *     +0x180000  TM   (Traffic Manager)
 *     +0x1c0000  PP   (Packet Processor)
 *   syscon  : zte,topcrm phandle        clock-mux for PON-side blocks
 *
 * Most of the bring-up is bit-exact replay of what stock's
 * plat-zxylzb_9128S.ko / tm.ko produce at boot, captured into static
 * tables (zx_stock_*.h, zx_cla_table.h, zx_pm_table.h, zx_npp_twin_data.h).
 * Some sub-blocks of that replay are now explicit named init functions;
 * the remainder go through a generic per-block apply walker.
 */

